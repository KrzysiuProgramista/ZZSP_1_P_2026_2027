C = float(input("Enter the temperature in celsius: "))
F = C * 9/5 + 32
K = C + 273.15
print(f"Celsius: {C}°C")
print(f"Fahrenheit: {F}°F")
print(f"Kelvin: {K}°K")
#  The difference between / and // is that a single slash divides the numbers normally while a double slash performs floor division (without the numbers after the dot)
