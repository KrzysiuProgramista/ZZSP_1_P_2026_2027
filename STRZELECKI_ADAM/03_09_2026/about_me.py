name=input("What is your name?")
age=input("What is your age?")
hometown=input("What is your hometown?")

print("Name: " + name)
print("Age: " + age)
print("Hometown: " + hometown)

# Sep(separator) is used to separate the values with a space example: print("Name:", name, "Age:", age, "Hometown:", hometown, sep="-")
# End(terminator) is used to end the print statement with a specific character example: print("Name:", name, "Age:", age, "Hometown:", hometown, end="!")
