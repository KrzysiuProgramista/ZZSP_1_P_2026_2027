celcius = float(input("Enter a temperature in Celcius: "))
farenheit = (celcius * 9/5 + 32)
kelvin = (celcius + 273.15)
print("Fahrenheit", farenheit,)
print("Kelvin", kelvin)

# Difference between / and //
# A single slash(/) divides numbers and leaves a floating point number.
result_float = 7/2 # Returns 3.5
# A double slash(//) divides numbers and rounds them to the nearest full number.
result_float = 7//2 # Returns 3
