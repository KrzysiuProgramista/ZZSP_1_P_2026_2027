days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]

print("Working days:", days[0:5])
print("Weekend:", days[5:7])
print("Days in reverse order:", days[::-1])

# Difference between remove(), pop() and del:

# remove(value)  → removes the first matching value (no return)
# pop(index)     → removes by index and RETURNS the value
# del lst[index] → deletes by index (no return, not a method)
